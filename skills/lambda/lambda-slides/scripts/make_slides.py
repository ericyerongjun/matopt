#!/usr/bin/env python3
"""Build a 16:9 LAMBDA-style insight deck from figures and takeaways."""

from __future__ import annotations

import argparse
from datetime import date
from pathlib import Path

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import MSO_AUTO_SIZE, PP_ALIGN
from pptx.util import Inches, Pt

COLORS = {
    "blue": RGBColor(37, 99, 235),
    "bg": RGBColor(244, 246, 248),
    "white": RGBColor(255, 255, 255),
    "ink": RGBColor(20, 24, 33),
    "muted": RGBColor(83, 91, 105),
    "line": RGBColor(225, 229, 235),
}
FONT = "Aptos"
CJK_FONT = "Noto Sans CJK SC"


def fill(shape, color):
    shape.fill.solid()
    shape.fill.fore_color.rgb = color
    shape.line.fill.background()


def add_text(slide, text, x, y, w, h, size=22, bold=False, color="ink", align=None, font=FONT):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.auto_size = MSO_AUTO_SIZE.TEXT_TO_FIT_SHAPE
    p = tf.paragraphs[0]
    p.text = text
    p.font.name = font
    p.font.size = Pt(size)
    p.font.bold = bold
    p.font.color.rgb = COLORS[color]
    if align:
        p.alignment = align
    return box


def add_bullet(slide, text, x, y, w, h, size=18, color="ink", font=FONT):
    return add_text(slide, "• " + text, x, y, w, h, size=size, color=color, font=font)


def add_panel(slide, x, y, w, h):
    panel = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    panel.fill.solid()
    panel.fill.fore_color.rgb = COLORS["white"]
    panel.line.color.rgb = COLORS["line"]
    return panel


def blank_slide(prs):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = COLORS["bg"]
    header = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), prs.slide_width, Inches(1.15))
    fill(header, COLORS["blue"])
    return slide


def fit_picture(slide, image_path, x, y, w, h):
    pic = slide.shapes.add_picture(str(image_path), Inches(x), Inches(y))
    max_w, max_h = Inches(w), Inches(h)
    scale = min(max_w / pic.width, max_h / pic.height)
    pic.width = int(pic.width * scale)
    pic.height = int(pic.height * scale)
    pic.left = Inches(x) + int((max_w - pic.width) / 2)
    pic.top = Inches(y) + int((max_h - pic.height) / 2)
    return pic


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--title", required=True)
    parser.add_argument("--subtitle", default="Evidence, implications, and next checks.")
    parser.add_argument("--out", default="slides.pptx")
    parser.add_argument("figures", nargs="*", help="Image paths to place on insight slides")
    args = parser.parse_args()

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    cover = blank_slide(prs)
    add_text(cover, args.title, 0.7, 0.24, 11.9, 0.62, size=32, bold=True, color="white", font=CJK_FONT)
    add_text(cover, args.subtitle, 0.9, 2.35, 9.2, 0.8, size=22, color="ink", font=CJK_FONT)
    accent = cover.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.9), Inches(3.35), Inches(2.8), Inches(0.08))
    fill(accent, COLORS["blue"])
    add_text(cover, "LAMBDA", 0.9, 6.35, 2.3, 0.35, size=15, bold=True, color="blue")
    add_text(cover, str(date.today()), 10.0, 6.35, 2.3, 0.3, size=11, color="muted", align=PP_ALIGN.RIGHT)

    page = 2
    for fig in args.figures:
        path = Path(fig)
        if not path.is_file():
            continue
        slide = blank_slide(prs)
        title = path.stem.replace("_", " ").replace("-", " ").title()
        add_text(slide, title, 0.7, 0.24, 11.9, 0.62, size=28, bold=True, color="white", font=CJK_FONT)
        add_panel(slide, 0.35, 1.45, 8.05, 4.75)
        fit_picture(slide, path, 0.55, 1.62, 7.65, 4.38)
        add_panel(slide, 8.72, 1.65, 3.95, 4.55)
        add_text(slide, "Key Finding", 9.08, 2.02, 3.25, 0.42, size=20, bold=True, color="blue", font=CJK_FONT)
        add_bullet(slide, "Describe the visible pattern with a number.", 9.08, 2.72, 3.15, 0.9, font=CJK_FONT)
        add_text(slide, "Generated by LAMBDA · https://lambda.com.ai", 0.65, 7.12, 6.2, 0.2, size=7, color="muted")
        add_text(slide, str(page), 12.25, 7.12, 0.45, 0.2, size=7, color="muted", align=PP_ALIGN.RIGHT)
        page += 1

    out = Path(args.out)
    prs.save(out)
    print(f"Saved {out.resolve()}")


if __name__ == "__main__":
    main()
