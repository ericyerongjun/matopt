#!/usr/bin/env python3
"""Generate UI wire types from Pydantic's JSON Schema (no npm dependency).

Run backend/.venv/bin/python -m app.ui.generate from backend first, then this
script. --check verifies the committed frontend contract without rewriting it.
Defaults are present in serialized wire models; nullable fields may be omitted
by model_dump(exclude_none=True). The renderer also accepts omitted children.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "backend/app/ui/contract.schema.json"
TARGET = ROOT / "frontend/src/types/ui.ts"

def name(value: str) -> str:
    return "JSONValue" if value == "JsonValue" else value

def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return name(schema["$ref"].split("/")[-1])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        extra = schema.get("additionalProperties", {})
        return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'JSONValue'}>"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(kind, "JSONValue")

def generate() -> str:
    schema = json.loads(SCHEMA.read_text())
    models = {**schema.get("$defs", {}), "UISurface": schema}
    lines = ["/** Generated by scripts/generate_ui_types.py from backend/app/ui/contract.schema.json. */",
             'export type JSONValue = null | boolean | number | string | JSONValue[] | { [key: string]: JSONValue };']
    for model_name, model in models.items():
        if model_name == "JsonValue":
            continue
        lines.append(f"export interface {name(model_name)} {{")
        for key, prop in model.get("properties", {}).items():
            nullable = any(item.get("type") == "null" for item in prop.get("anyOf", []))
            optional = "?" if nullable or key == "children" else ""
            lines.append(f"    {key}{optional}: {ts_type(prop)};")
        lines.append("}")
    lines += ['export type UINodeType = UINode["type"];',
              "export interface UICapabilities {",
              "    version: 1;", "    native: boolean;", "    mini_apps: boolean;", "    node_types: UINodeType[];", "}", ""]
    return "\n".join(lines)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != generated:
            parser.exit(1, "UI types differ from the server schema; run scripts/generate_ui_types.py\n")
        print("UI types match the server schema")
    else:
        TARGET.write_text(generated)
        print(f"Wrote {TARGET.relative_to(ROOT)}")
